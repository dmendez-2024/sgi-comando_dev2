package com.cajamarca.sgi.comando.storage;

import java.io.*;
import java.nio.file.*;

/** Detecta el tipo real de una imagen por sus bytes mágicos; no confía en la extensión ni en el Content-Type del cliente. */
public final class ImageSniffer {
    private ImageSniffer() {}

    public static String detect(byte[] b) {
        if (b == null || b.length < 3) return null;
        if ((b[0] & 0xFF) == 0xFF && (b[1] & 0xFF) == 0xD8 && (b[2] & 0xFF) == 0xFF) return "image/jpeg";
        if (b.length >= 8 && (b[0] & 0xFF) == 0x89 && b[1] == 'P' && b[2] == 'N' && b[3] == 'G' && b[4] == 0x0D && b[5] == 0x0A && b[6] == 0x1A && b[7] == 0x0A) return "image/png";
        if (b.length >= 12 && b[0] == 'R' && b[1] == 'I' && b[2] == 'F' && b[3] == 'F' && b[8] == 'W' && b[9] == 'E' && b[10] == 'B' && b[11] == 'P') return "image/webp";
        return null;
    }

    public static String detect(Path file) throws IOException {
        try (InputStream in = Files.newInputStream(file)) { return detect(in.readNBytes(12)); }
    }

    public static String extension(String contentType) {
        return switch (contentType) {
            case "image/jpeg" -> "jpg";
            case "image/png" -> "png";
            case "image/webp" -> "webp";
            default -> "bin";
        };
    }
}
